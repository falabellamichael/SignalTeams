import { chromium } from "file:///D:/VehicleSite/node_modules/playwright/index.mjs";
const B = "http://127.0.0.1:8075";
const errors = [], failed = [];
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
page.on("requestfailed", (r) => failed.push(r.url()));
page.on("response", (r) => { if (r.status() >= 400) failed.push(`${r.status()} ${r.url()}`); });
await page.goto(B, { waitUntil: "networkidle" });
await page.waitForSelector('button:has-text("crew account")', { timeout: 8000 });
await page.click('button:has-text("crew account")');
await page.waitForSelector('input:not([type])', { timeout: 5000 });
await page.fill('input:not([type])', "mike");
await page.locator('input[type="password"]').first().fill("password");
await page.click('button:has-text("Sign in"), button:has-text("sign in")');
await page.waitForSelector(".rail", { timeout: 10000 });
await page.waitForTimeout(1000);
await page.click('.nav-item:has-text("Library")');
await page.waitForTimeout(1800);
console.log("trend strip:", await page.locator(".trend-strip").count());
console.log("trend cards:", await page.locator(".trend-card").count());
console.log("first:", await page.locator(".trend-card").first().textContent());
console.log("summons stat on cards:", await page.locator(".stat:has-text('✦')").count());
// sort by Most summoned
await page.click('.chip:has-text("Most summoned")');
await page.waitForTimeout(1200);
const first = await page.locator(".agent-grid .agent-card, .agent-grid > *").first().textContent();
console.log("top card:", (first || "").slice(0, 60));
await page.screenshot({ path: "qa-trend.png" });
console.log("CONSOLE:", errors.length ? errors.slice(0, 4) : "clean");
console.log("FAILED:", failed.length ? failed.slice(0, 4) : "none");
await browser.close();
